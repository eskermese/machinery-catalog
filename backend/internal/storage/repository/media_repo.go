package repository

import "context"

// MediaStorage исходящий порт хранилища изображений.
//
// Порт живёт здесь вместе с остальными исходящими портами персистентности:
// файл на диске — такая же внешняя память, как строка в таблице, и сервису
// не должно быть видно, лежит она рядом или в объектном хранилище.
//
// Оба метода принимают готовый путь: имя файла придумывает домен
// (entity.NewStoredImage), а адаптеру остаётся положить или убрать байты
// по адресу.
type MediaStorage interface {
	// Save записывает файл по пути внутри хранилища.
	// Путь приходит из домена и отделён от корня хранилища.
	Save(ctx context.Context, path string, content []byte) error
	// Delete удаляет файл по пути внутри хранилища.
	//
	// Отсутствие файла — не ошибка: удаление вызывается после того, как
	// строка карточки уже исчезла, и повторный вызов не должен ронять
	// операцию, которая по сути уже завершилась.
	Delete(ctx context.Context, path string) error
}

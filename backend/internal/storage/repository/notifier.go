package repository

import (
	"context"

	"github.com/eskermese/machinery-catalog/backend/internal/domain/entity"
)

// Notifier исходящий порт уведомлений.
//
// Порт живет здесь, а не в отдельном пакете, по двум причинам. Во-первых,
// единственная его реализация — запись в таблицу notification_outbox, то есть
// персистентность, а исходящие порты персистентности по договоренности лежат
// в этом пакете. Во-вторых, сервисы уже зависят от него ради репозиториев,
// и новый пакет добавил бы зависимость, не добавив границы.
//
// Метод один намеренно: доменное событие самодостаточно, а выбор канала,
// шаблона и способа доставки остается за адаптером, которого еще нет.
type Notifier interface {
	// Notify принимает доменное событие к доставке.
	// Вызывается вне бизнес-транзакции, ошибка не должна влиять на сценарий.
	Notify(ctx context.Context, event *entity.DomainEvent) error
}

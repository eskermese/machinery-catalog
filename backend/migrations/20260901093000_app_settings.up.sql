-- Настройки приложения, которые переключает администратор.
--
-- Почему таблица, а не переменная окружения: переключать их должен человек
-- из интерфейса, а не разработчик развёртыванием. Переменная окружения
-- требует перезапуска сервиса и доступа к инфраструктуре — для флага
-- «показывать ли цену в долларах» это несоразмерно.
--
-- Почему ключ-значение, а не колонка на настройку: настройка здесь пока одна,
-- и таблица с одной колонкой на каждый будущий флаг потребовала бы миграции
-- на каждый из них. Тип значения знает читающий код — он же и единственный,
-- кто знает смысл ключа.

CREATE TABLE IF NOT EXISTS app_settings
(
    key        text PRIMARY KEY,
    value      text        NOT NULL,
    updated_at timestamptz NOT NULL DEFAULT now(),

    CONSTRAINT app_settings_key_not_blank CHECK (btrim(key) <> '')
);

COMMENT ON TABLE app_settings IS
    'Настройки, переключаемые администратором из интерфейса. Ключ-значение: смысл ключа и тип значения знает читающий код';
COMMENT ON COLUMN app_settings.value IS
    'Значение строкой. Разбор — на стороне читающего кода: тип настройки знает только он';

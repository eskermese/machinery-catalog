-- Ручной курс можно исправить, не нарушая append-only.
--
-- Задача. Администратор ввёл курс за сегодня с опечаткой. Исправить его
-- было нечем: ограничение уникальности (source, пара, дата) не давало
-- ввести второй ручной курс за ту же дату, а править строку нельзя —
-- таблица append-only, и это правило держит воспроизводимость истории.
--
-- Решение. Ограничение остаётся для ВНЕШНИХ источников и снимается
-- с ручного ввода. Смысл у них разный: повторная загрузка воркером за ту же
-- дату — это сбой расписания, и она обязана конфликтовать; повторный ручной
-- ввод — осознанное исправление человека, и оно обязано проходить.
--
-- Ничего не перезаписывается: исправление — НОВАЯ строка с более поздним
-- fetched_at, а действующим считается последний по fetched_at (см. GetLatest).
-- История опечатки сохраняется и видна.

ALTER TABLE fx_rates DROP CONSTRAINT IF EXISTS fx_rates_source_pair_date_unique;

CREATE UNIQUE INDEX IF NOT EXISTS fx_rates_external_source_pair_date_uidx
    ON fx_rates (source, base_currency, quote_currency, rate_date)
    WHERE source <> 'manual';

COMMENT ON INDEX fx_rates_external_source_pair_date_uidx IS
    'Один внешний источник даёт один курс пары в сутки. Ручной ввод исключён: повторный ввод человеком — исправление опечатки, и он обязан проходить новой строкой';

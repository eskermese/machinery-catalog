/**
 * Что клиент вводит по умолчанию.
 *
 * Это допущения о РЕЖИМЕ РАБОТЫ и ценах вокруг машины, а не о самой машине:
 * их клиент видит в полях и меняет под себя. Величины о машине — расход
 * топлива, интервал и стоимость ТО, остаточная стоимость — по умолчанию
 * не подставляются никогда: расчёт с потолочным расходом выглядит расчётом,
 * а является догадкой.
 *
 * Пять лет и полторы тысячи моточасов в год — обычный горизонт разговора
 * о технике: столько живёт лизинговый договор, и столько машина отрабатывает
 * при односменной работе.
 */
export const TCO_DEFAULTS = {
  years: 5,
  hoursPerYear: 1500,
  /** 290 ₸ за литр дизеля. */
  fuelPriceKztCents: 29_000,
  /** 2500 ₸ за моточас работы оператора. */
  operatorHourlyKztCents: 250_000,
}

/**
 * Сколько величин о машине может не хватать, чтобы расчёт ещё имел смысл.
 *
 * Их четыре: расход топлива, интервал ТО, стоимость ТО, остаточная стоимость.
 * Половина — граница: при трёх недостающих в расчёте остаются покупка
 * и оператор, то есть цена и арифметика, которую клиент сделает в уме.
 * Показывать это как «стоимость владения» — выдавать пустоту за расчёт.
 */
export const TCO_MAX_MISSING = 2

/** Недостающая величина словами: клиенту нужен не код, а что именно не заведено. */
const MISSING_LABELS: Record<string, string> = {
  fuel_consumption: 'расход топлива',
  service_interval: 'интервал ТО',
  service_cost: 'стоимость ТО',
  residual_value: 'остаточная стоимость',
}

/**
 * Чего не хватило строке — словами, без того, что и так сказано её названием.
 *
 * `own` — величина, о которой строка и есть: в строке «Остаточная стоимость»
 * дописывать «нет данных: остаточная стоимость» незачем, название уже сказало.
 * А строке «Плановое обслуживание» нужны две величины сразу, и какой именно
 * не хватило — новость, которую иначе неоткуда узнать.
 *
 * Возвращает null, когда добавить нечего.
 */
export function missingLabel(codes: string[] | undefined, own?: string): string | null {
  const rest = (codes ?? []).filter((code) => code !== own)
  if (rest.length === 0) return null

  return rest.map((code) => MISSING_LABELS[code] ?? code).join(', ')
}

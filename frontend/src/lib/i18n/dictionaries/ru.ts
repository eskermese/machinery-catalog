/**
 * Русский словарь — источник правды.
 *
 * Из него выводится тип Dictionary, и остальные языки обязаны его повторить
 * до последнего ключа: забытая строка станет ошибкой сборки, а не пустым
 * местом на странице у того, кто читает не по-русски.
 *
 * Строки с подстановкой — функции, а не шаблоны с плейсхолдерами. Так
 * склонение остаётся внутри языка: «нашлось 5 машин» и «found 5 machines»
 * считаются по разным правилам, и общей функции plural, знающей про оба,
 * быть не должно — она неизбежно окажется написанной под один из них.
 */
/**
 * Русское склонение по числу.
 *
 * Правило: 1 — первая форма, 2–4 — вторая, остальное — третья;
 * числа 11–14 всегда третья.
 *
 * Живёт здесь, а не в общем месте: это правило РУССКОГО языка, и в общем
 * файле оно рано или поздно было бы вызвано для английского, где счётных
 * форм две, а не три.
 *
 * Экспортируется для админки и коммерческого предложения: они остаются
 * русскими, и своих счётных форм у них хватает — «17 карточек»,
 * «3 подраздела». Витрина им не пользуется: там счётная форма приходит
 * из словаря того языка, на котором читают страницу.
 */
export function plural(count: number, one: string, few: string, many: string): string {
  const mod100 = Math.abs(count) % 100
  if (mod100 >= 11 && mod100 <= 14) return many

  const mod10 = mod100 % 10
  if (mod10 === 1) return one
  if (mod10 >= 2 && mod10 <= 4) return few

  return many
}


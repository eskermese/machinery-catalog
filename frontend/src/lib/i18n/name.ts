import type { Locale } from './config'

/**
 * Всё, у чего есть название на трёх языках: раздел, характеристика,
 * вариант, карточка, программа лизинга.
 *
 * Тип структурный, а не перечисление сущностей: он описывает форму, и
 * новая сущность с теми же тремя полями подойдёт сама.
 */
export type Translated = {
  nameRU: string
  nameKK?: string
  nameEN?: string
}

/**
 * Название на языке страницы, с откатом на русский.
 *
 * Правило одно на весь каталог: русское обязательно, остальные пусты, пока
 * перевода нет (см. проверку на бэкенде). Пустое поле — это «не перевели»,
 * и показать вместо него русское честнее, чем пустое место: человек,
 * читающий английскую витрину, скорее разберёт «Гусеничный экскаватор
 * XE370G», чем строку без названия.
 *
 * Наполовину переведённый каталог — нормальное состояние: 456 карточек
 * переводятся не за один вечер, а витрина обязана работать всё это время.
 */
export function localizedName(item: Translated, locale: Locale): string {
  return pick(item, locale) || item.nameRU
}

/*
  Switch без ветки default и есть проверка на полноту: пока в нём разобраны
  все языки из Locale, компилятор видит, что функция всегда возвращает
  строку. Добавив язык в LOCALES и забыв про эту функцию, получим ошибку
  типов, а не молчаливый русский на английской странице.
*/
function pick(item: Translated, locale: Locale): string {
  switch (locale) {
    case 'ru':
      return item.nameRU
    case 'en':
      return item.nameEN ?? ''
    case 'kk':
      return item.nameKK ?? ''
  }
}

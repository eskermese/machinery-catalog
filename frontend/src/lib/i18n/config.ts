/**
 * Языки витрины.
 *
 * Порядок здесь — порядок в переключателе. Русский первый: это язык
 * по умолчанию и язык, на котором заведён каталог.
 *
 * Казахский обозначен `kk`, а не `kz`: kk — код ЯЗЫКА по ISO 639-1, kz —
 * код страны. Тем же кодом названы поля в базе (nameKK), и расходиться
 * им незачем. В переключателе он подписан «Қазақша» — посетителю нужен
 * не код, а название на его языке.
 *
 * Английский включён после того, как словарь был переведён целиком.
 * До этого он намеренно отсутствовал: страница, переведённая наполовину,
 * хуже честно одноязычной — открывший /en вправе ожидать английский,
 * а не вперемешку.
 */
export const LOCALES = ['ru', 'en', 'kk'] as const

/** Язык по умолчанию: на него уходит корень сайта и всё, что без префикса. */
export const DEFAULT_LOCALE: Locale = 'ru'

export type Locale = (typeof LOCALES)[number]

/**
 * Заголовок, которым прокси сообщает язык серверным компонентам.
 *
 * Нужен ровно одному месту — корневой раскладке, где стоит <html lang>.
 * Она лежит ВЫШЕ сегмента [lang] (под ней живут и админка, и вход, и
 * публичное КП, которые языка не знают), поэтому прочитать язык из адреса
 * там нечем. Тот же приём уже применён в проекте для пути страницы,
 * см. PATHNAME_HEADER.
 */
export const LOCALE_HEADER = 'x-techline-locale'

/** Известен ли нам такой язык. Сужает тип, чтобы не проверять дважды. */
export function isLocale(value: string): value is Locale {
  return (LOCALES as readonly string[]).includes(value)
}

/**
 * Первый сегмент пути, если это язык.
 *
 * Одна реализация на прокси, серверные компоненты и браузер: разъехавшись,
 * они дали бы разный язык на одной и той же странице.
 */
export function localeFromPathname(pathname: string): Locale | null {
  const first = pathname.split('/')[1] ?? ''

  return isLocale(first) ? first : null
}

/**
 * Адрес внутри витрины с языковым префиксом.
 *
 * Внешние адреса, якоря и уже приставленный префикс не трогает: через эту
 * функцию проходят все ссылки витрины, и она обязана быть безвредной для
 * того, что префикса не требует.
 */
export function localePath(locale: Locale, path: string): string {
  if (!path.startsWith('/')) return path
  if (localeFromPathname(path) !== null) return path

  // Корень витрины — это `/ru`, а не `/ru/`: хвостовой слеш дал бы второй
  // адрес у той же страницы.
  return path === '/' ? `/${locale}` : `/${locale}${path}`
}

/**
 * Путь без языкового префикса: `/ru/compare` → `/compare`.
 *
 * Нужен там, где код узнаёт страницу по адресу. После переезда витрины
 * под сегмент [lang] сравнения вида `pathname === '/compare'` перестали
 * срабатывать молча: путь стал `/ru/compare`, условие — ложным, и
 * страница повела себя как чужая. Так на странице сравнения снова
 * появилась полоса набранного, а на главной — второе поле поиска.
 *
 * Отдельная функция, а не regex по месту: мест несколько, и разъехавшись,
 * они дали бы разное представление о том, на какой мы странице.
 */
export function pathWithoutLocale(pathname: string): string {
  return localeFromPathname(pathname) === null ? pathname : pathname.replace(/^\/[^/]+/, '') || '/'
}

/**
 * Канонический адрес страницы и её версии на других языках.
 *
 * Поисковику двуязычный сайт без этого выглядит как две несвязанные
 * страницы с похожим содержимым: он выбирает одну и показывает её всем,
 * включая тех, кому нужна другая. Связывает их hreflang, и объявлять его
 * обязаны ОБЕ страницы, каждая — про себя и про соседа.
 *
 * `path` — адрес без языкового префикса, каким он написан в маршруте.
 */
export function localeAlternates(locale: Locale, path: string) {
  return {
    canonical: localePath(locale, path),
    languages: Object.fromEntries(LOCALES.map((item) => [item, localePath(item, path)])),
  }
}

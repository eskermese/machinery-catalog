/**
 * Адрес публичной страницы предложения.
 *
 * Одно место на всю сборку ссылки: адрес встречается и в админке при выпуске,
 * и в разметке самой страницы, и разъехавшись однажды, они дали бы менеджеру
 * ссылку, ведущую в никуда.
 */
export function quoteHref(token: string): string {
  return `/quote/${encodeURIComponent(token)}`
}

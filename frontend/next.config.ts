import type { NextConfig } from 'next'

/**
 * Адрес бэкенда без суффикса /api — из него берётся раздача фотографий.
 *
 * Бэкенд отдаёт в поле url путь вида «/media/machines/….jpg», то есть
 * относительный: он рассчитан на то, что клиент дописывает его к адресу,
 * по которому и так обращается к API.
 */
function backendOrigin(): string {
  const base = process.env.API_BASE_URL?.trim() || 'http://localhost:8000/api'

  return base.replace(/\/+$/, '').replace(/\/api$/, '')
}

const nextConfig: NextConfig = {
  /**
   * Домены, с которых dev-серверу разрешено отдавать свои ресурсы.
   *
   * Нужно, чтобы стенд можно было показать с телефона через туннель.
   * По умолчанию Next отдаёт /_next/static только на тот же адрес, с которого
   * открыта страница; с чужого домена HTML приходит, а часть чанков — нет.
   * Выглядит это не как ошибка загрузки, а как мёртвая страница: React
   * не стартует, и НИ ОДНА кнопка не отвечает, хотя разметка на месте.
   *
   * Список действует ТОЛЬКО в dev: в сборке этой настройки нет, и открывать
   * ею что-либо в проде нечего. Быстрый туннель Cloudflare выдаёт новое имя
   * при каждом запуске, поэтому здесь маска, а не конкретный адрес, — иначе
   * конфигурацию пришлось бы править перед каждым показом.
   */
  allowedDevOrigins: ['*.trycloudflare.com'],

  async rewrites() {
    return [
      {
        // Фотографии раздаёт бэкенд, но браузер ходит на наш же домен:
        // адрес бэкенда не попадает в разметку, и CORS не при чём —
        // ровно та же причина, по которой запросы к API идут через /api/proxy.
        source: '/media/:path*',
        destination: `${backendOrigin()}/media/:path*`,
      },
    ]
  },
}

export default nextConfig

/**
 * Делит название карточки на переводимую часть и обозначение модели.
 *
 * «Гусеничный экскаватор XE370G» → «Гусеничный экскаватор» + «XE370G».
 *
 * Разрез идёт по первому слову С ЛАТИНСКОЙ БУКВОЙ, а не по первой цифре.
 * По цифре нельзя: у полусотни карточек в названии есть скобочное пояснение
 * с числом — «Скребок для травы (модель 2024 года, удлинённый)», — и разрез
 * по цифре рвал его посередине, оставляя незакрытую скобку в обеих половинах.
 * Обозначения же моделей латинские всегда: XE370G, ZL50GN, XCMG Hanvan G7.
 *
 * Модель не переводится ни на один язык: она одинакова везде, и «перевести»
 * её значило бы испортить.
 *
 * Функция обязана быть ОДНА на сборку SQL и на выписку непереведённого:
 * разойдясь, они дали бы разные ключи глоссария для одного названия.
 *
 * Строка приводится к NFC. В источнике «й» местами записана РАЗЛОЖЕННОЙ —
 * «и» плюс комбинирующая краткость вместо одного символа, — и такие
 * названия внешне неотличимы от обычных, но не совпадают с ключом
 * глоссария ни одним сравнением. Три карточки из 456; найдены только
 * потому, что одна из них не нашла свой перевод.
 */
export function splitMachineName(rawName) {
  const name = rawName.normalize('NFC')
  const tokens = name.split(' ')

  for (let i = 0; i < tokens.length; i += 1) {
    if (/[A-Za-z]/.test(tokens[i])) {
      return { type: tokens.slice(0, i).join(' ').trim(), model: tokens.slice(i).join(' ').trim() }
    }
  }

  return { type: name.trim(), model: '' }
}

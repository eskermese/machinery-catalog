-- Данные стенда, которых нет в дампе сайта: наценка к курсу, программы
-- лизинга и кривые остаточной стоимости.
--
-- Каталог наполняет import.mjs, но вокруг цены построено ещё три вещи —
-- пересчёт в тенге, калькулятор лизинга и выпуск коммерческого предложения.
-- Курс для первого тянет воркер из выдачи Нацбанка, а программ лизинга
-- в источнике не было: на сайте компании таких данных нет.
--
-- ЭТО ДЕМОНСТРАЦИОННЫЕ ЗНАЧЕНИЯ: программы придуманы и партнёров не называют,
-- кривые остаточной стоимости взяты порядком величины, а не из оценок рынка.
-- В работе программы и кривые заводит администратор в админке.
--
-- Важно, чем кривые ОТЛИЧАЮТСЯ от расхода топлива и интервалов ТО, которых
-- здесь нет и не будет. Расход — свойство конкретной машины, и выдуманный
-- он даёт расчёт, выглядящий расчётом: проверить его по карточке нельзя.
-- Кривая же — решение компании о том, как техника теряет в цене, оно
-- заводится руками в админке и там же видно целиком.
--
-- Файл повторно запускаемый: сначала чистит своё, потом заводит заново.

DELETE FROM fx_markups;
DELETE FROM fx_rates;
DELETE FROM leasing_programs;
DELETE FROM residual_value_curves;

-- КУРСА ЗДЕСЬ НЕТ, И ЭТО РЕШЕНИЕ.
--
-- Раньше сюда заводился демонстрационный курс, чтобы стенд без сети показывал
-- хоть какие-то цены в тенге. Теперь подключён настоящий источник — официальная
-- выдача Нацбанка Казахстана, — и запасное число стало вредным: оно
-- неотличимо от загруженного и превращает «курс не приехал» в тихо неверную
-- цену. Пустая строка на витрине видна, ошибка в третьем знаке — нет.
--
-- Без сети витрина честно показывает цену в юанях и молчит про тенге.
-- Это верное поведение: тенговой цены в этот момент действительно никто
-- не знает.
--
-- Ручного курса здесь тоже нет, и по той же причине. Приоритет «ручной курс
-- главнее курса Нацбанка» означает, что заведённое здесь число перебило бы
-- настоящую выдачу и осталось бы в силе навсегда: воркер его не обновит.
-- Курс заводит менеджер в админке — там видно и дату, и рядом стоящий
-- курс Нацбанка.
--
-- Строку fx_markups это не отменяет: нулевая наценка — не выдуманное
-- значение, а описание того, что наценки нет.

-- Наценка нулевая: сервис работает и без неё, а ненулевая на стенде только
-- запутала бы — цена в тенге не сходилась бы с курсом при проверке руками.
--
-- Пары две, потому что и цен на витрине две: тенге считается по CNY→KZT,
-- доллар — по CNY→USD, каждая со своей наценкой. Одна строка на обе означала
-- бы, что наценку нельзя задать порознь, а это ровно то, чего требует
-- заказчик.
INSERT INTO fx_markups (base_currency, quote_currency, markup_bps, effective_from)
VALUES
    ('CNY', 'KZT', 0, now() - interval '1 day'),
    ('CNY', 'USD', 0, now() - interval '1 day');


/** Машинный ключ характеристики из её названия. */
export function toCode(name) {
  const base = normalizeName(name)
    .split('')
    .map((char) => TRANSLIT[char] ?? char)
    .join('')
    .replace(/[^a-z0-9]+/g, '_')
    .replace(/^_+|_+$/g, '')

  // Подчёркивания срезаем после обрезки, а не до: длина ограничена, и рез
  // посреди слова оставлял бы хвостовой разделитель, который база не примет.
  return base.slice(0, 60).replace(/_+$/, '') || 'attr'
}

/** Значение похоже на число. */
export function isNumeric(value) {
  return /^[≥≤~<>]?\s*\d[\d   ]*(?:[.,]\d+)?$/.test(value)
}

/** Число из значения источника: «25 000» -> «25000», «1,8» -> «1.8». */
export function toNumber(value) {
  return value.replace(/[≥≤~<>\s  ]/g, '').replace(',', '.')
}

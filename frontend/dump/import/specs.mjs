const BY_VARIANT = new Map()
for (const group of SYNONYMS) for (const variant of group.of) BY_VARIANT.set(variant, group)

/** Название к единому виду: регистр, пробелы, хвостовая пунктуация. */
export function normalizeName(name) {
  return name
    .toLowerCase()
    .replace(/\s+/g, ' ')
    .replace(/[.:;,]+$/, '')
    .trim()
}

/** Каноническое название и единица; для неизвестных — как в источнике. */
export function canonical(spec) {
  const key = normalizeName(spec.name)
  const group = BY_VARIANT.get(key)
  if (group) return { key: group.name, name: group.name, unit: group.unit ?? spec.unit }

  const name = spec.name
    .replace(/\s+/g, ' ')
    .replace(/[.:;,]+$/, '')
    .trim()

  return { key, name: name.charAt(0).toUpperCase() + name.slice(1), unit: spec.unit }
}


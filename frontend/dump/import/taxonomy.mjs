/** Подраздел по названию товара; null — не узнали. */
export function classify(title) {
  const text = fold(title)

  for (const section of TAXONOMY) {
    // Раздел без подразделов сам является категорией товара. Заводить
    // единственного потомка с именем родителя нельзя: крошки тогда читаются
    // как «Запасные части → Запасные части → Двигатели».
    const candidates = section.children.length > 0 ? section.children : [section]

    for (const candidate of candidates) {
      if (candidate.exact?.some((name) => fold(name) === text)) return { section, child: candidate }
      if (candidate.match?.some((needle) => text.includes(fold(needle)))) {
        return { section, child: candidate }
      }
    }
  }

  return null
}

/**
 * Строка для сопоставления: нижний регистр и «ё» сведена к «е».
 *
 * Разбор дампа уже сводит «ё» в названиях товаров, но признаки в таблице
 * написаны как в русском языке — «быстросъём», «подъёмник». Складывать обе
 * стороны здесь надёжнее, чем помнить про это при каждой правке таблицы.
 */
function fold(value) {
  return value.toLowerCase().replace(/ё/g, 'е').trim()
}
